import { open, shot } from "./lib.mjs";
import { NEHA, body, small, hscroll } from "./bs7-employer-lib.mjs";
const s = await open({ port: 3502, ...NEHA, width: 375, height: 812, engine: "webkit", name: "bs7-emp-wk-checkout" });
const p = s.page;
await p.goto(s.url("/employer/checkout"), { waitUntil: "domcontentloaded" }); await p.waitForTimeout(3500);
console.log("hscroll", await hscroll(p), "small:", JSON.stringify(await small(p)));
console.log("controls:", JSON.stringify(await p.$$eval("main input, main button", (e) => e.filter(x=>x.getBoundingClientRect().width>0).map((x) => `${x.name||x.innerText.trim().slice(0,22)}:${x.type||""}:im=${x.inputMode||""}:${Math.round(x.getBoundingClientRect().width)}x${Math.round(x.getBoundingClientRect().height)}`))));
const pay = p.getByRole("button", { name: /Complete for free/ });
await pay.evaluate((e) => e.scrollIntoView({ block: "center" })); await p.waitForTimeout(800);
const bb = await pay.boundingBox();
const hit = await p.evaluate(({ x, y }) => { const e = document.elementFromPoint(x, y); return e ? (e.tagName + ":" + (e.innerText || "").slice(0, 30)) : null; }, { x: bb.x + bb.width / 2, y: bb.y + bb.height / 2 });
console.log("pay btn box", JSON.stringify(bb), "element at centre:", hit);
await shot(s, "bs7-emp-wk-checkout-pay", { fullPage: false });
console.log("tot:", (await body(p)).match(/Order summary.{0,260}/)?.[0]);
await pay.click({ force: true }); await p.waitForTimeout(4500);
console.log("after pay:", new URL(p.url()).pathname, (await body(p)).slice(0, 600));
await shot(s, "bs7-emp-wk-after-pay", { fullPage: false });
console.log(s.errors);
await s.close();
