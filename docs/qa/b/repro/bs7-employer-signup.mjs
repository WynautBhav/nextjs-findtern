import { open, shot } from "./lib.mjs";
import { lastOtp, saveState, errsOf, body, small, hscroll } from "./bs7-employer-lib.mjs";
const ENGINE = process.argv[2] ?? "chromium";
const rnd = Math.floor(100000 + Math.random() * 899999);
const email = `qa.b.emp.${rnd}@acme-qa-test.in`;
const s = await open({ port: 3502, width: 375, height: 812, engine: ENGINE, name: `bs7-emp-signup-${ENGINE}` });
const p = s.page;
await p.goto(s.url("/employer/signup"), { waitUntil: "networkidle" });
// negative: personal mailbox
await p.locator("input[name=name]").fill("Qa Employer");
await p.locator("input[name=companyName]").fill("Acme QA Test");
await p.locator("input[name=companyEmail]").fill("someone@gmail.com");
await p.locator("input[name=phoneNumber]").fill("9645812073");
await p.locator("input[name=password]").fill("Qa#Tester2026");
await p.locator("input[type=checkbox]").first().check();
await p.waitForTimeout(1500);
console.log("submit disabled with gmail:", await p.getByRole("button", { name: /send verification code/i }).isDisabled());
console.log("gmail attempt:", (await body(p)).match(/(personal|company)[^.]{0,80}/i)?.[0], JSON.stringify(await errsOf(p)));
await shot(s, `bs7-emp-signup-gmail-${ENGINE}`, { fullPage: false });
await p.locator("input[name=companyEmail]").fill(email);
await p.waitForTimeout(1500);
await p.getByRole("button", { name: /send verification code/i }).click();
await p.waitForTimeout(2500);
console.log("after submit:", (await body(p)).slice(0, 300));
await shot(s, `bs7-emp-signup-otp-${ENGINE}`, { fullPage: false });
const otp = lastOtp(email);
console.log("otp", !!otp, email);
const box = p.locator("input[inputmode=numeric], input[autocomplete=one-time-code]").first();
console.log("otp attrs", await box.evaluate((e) => ({ type: e.type, im: e.inputMode, ac: e.autocomplete })).catch(() => "none"));
await box.fill(otp);
await p.getByRole("button", { name: /verify|create|continue/i }).first().click();
await p.waitForTimeout(4000);
console.log("landed:", new URL(p.url()).pathname);
console.log(await body(p).then((t) => t.slice(0, 500)));
saveState(ENGINE === "webkit" ? { emailW: email } : { email });
await shot(s, `bs7-emp-signup-after-${ENGINE}`, { fullPage: false });
console.log("small:", await small(p), await hscroll(p));
console.log(s.errors);
await s.close();
console.log("EMAIL", email);
