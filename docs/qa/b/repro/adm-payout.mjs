import { open, shot, pick } from "./lib.mjs";
import { dump } from "./dump.mjs";
const s = await open({ port: 3502, ...pick("admin"), width: 375, name: "adm-payout" });
const p = s.page;
await p.goto(s.url("/admin/payouts?status=pending"), { waitUntil: "networkidle" });
const before = await p.getByRole("button", { name: "Edit payout status" }).count();
await p.getByRole("button", { name: "Edit payout status" }).first().click();
await p.waitForTimeout(700);
console.log("dialog:", (await p.evaluate(() => document.querySelector("[role=dialog]")?.innerText.replace(/\s+/g, " ") ?? "")).slice(0, 400));
console.log(JSON.stringify((await dump(p)).filter((c) => /dialog|status|reference|save|cancel|paid|mark|failed/i.test(c.l) || c.t.startsWith("input") || c.t === "select").map((c) => `${c.t}:${c.l}:${c.w}x${c.h}`)));
await shot(s, "adm-payout-dialog-375", { fullPage: false });
await p.locator("button:text-is(\"Paid\"), [role=radio]:text-is(\"Paid\")").first().click();
await p.getByRole("button", { name: /^done$/i }).click();
await p.waitForTimeout(1000);
console.log("Done without reference →", JSON.stringify(await p.$$eval("[role=alert], .text-danger, [role=status]", (e) => e.map((x) => x.textContent.trim()).filter(Boolean))));
await p.getByPlaceholder(/UTR/i).fill("UTR" + Date.now().toString().slice(-8));
await p.getByRole("button", { name: /^done$/i }).click();
await p.waitForTimeout(2500);
console.log("pending rows before/after:", before, await p.getByRole("button", { name: "Edit payout status" }).count());
console.log(JSON.stringify(await p.$$eval("[role=status], [data-sonner-toast]", (e) => e.map((x) => x.textContent.trim()))));
console.log(s.errors);
await s.close();
