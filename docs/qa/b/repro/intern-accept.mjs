import { open, shot, pickOr as pick } from "./lib.mjs";
const W = Number(process.argv[2] ?? 375), ENGINE = process.argv[3] ?? "chromium", ID = process.argv[4];
const s = await open({ port: 3502, ...pick("intern"), width: W, engine: ENGINE, name: `intern-accept-${W}-${ENGINE}` });
const p = s.page;
const body = () => p.evaluate(() => document.querySelector("main")?.innerText.replace(/\s+/g, " ") ?? "");
await p.goto(s.url(`/intern/proposals/${ID}`), { waitUntil: "networkidle" });
await p.getByRole("button", { name: /accept this offer/i }).click();
await p.waitForTimeout(1000);
await shot(s, `intern-accept-dialog-${W}-${ENGINE}`, { fullPage: false });
console.log("dialog/after click:", (await p.evaluate(() => (document.querySelector("[role=dialog]")?.innerText || "").replace(/\s+/g, " "))).slice(0, 700) || "(no dialog)");
console.log("dialog buttons:", JSON.stringify(await p.$$eval("[role=dialog] button, [role=dialog] input", (b) => b.map((x) => `${x.tagName}:${(x.innerText || x.getAttribute("aria-label") || x.type).trim().slice(0, 30)}:${Math.round(x.getBoundingClientRect().height)}`))));
const confirm = p.locator("[role=dialog]").getByRole("button", { name: /accept|confirm|yes/i }).last();
const cb = p.locator("[role=dialog] input[type=checkbox]");
if (await cb.count()) await cb.first().check({ force: true });
if (await confirm.count()) await confirm.click();
await p.waitForTimeout(2500);
console.log("after accept:", (await body()).slice(0, 700));
await shot(s, `intern-accepted-${W}-${ENGINE}`, { fullPage: false });
await p.goto(s.url("/intern/timesheets"), { waitUntil: "networkidle" });
console.log("timesheets:", (await body()).slice(0, 400));
await p.goto(s.url("/intern/dashboard"), { waitUntil: "networkidle" });
console.log("dashboard:", (await body()).slice(0, 500));
console.log(s.errors);
await s.close();
