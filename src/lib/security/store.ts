import { createReadStream } from "node:fs";
import { mkdir, readFile, rename, stat, unlink, writeFile } from "node:fs/promises";
import { dirname, join, normalize, resolve, sep } from "node:path";
import { randomUUID } from "node:crypto";
import { generateKey, type OpaqueKey } from "./sign.ts";

/**
 * Private file store for identity documents.
 *
 * ── The rule ──────────────────────────────────────────────────────────
 *
 * Nothing in here is ever served from a directory. There is no `public/`
 * mount and no static route. The only way to read a file is to redeem a valid
 * signed token whose subject matches the authenticated caller.
 *
 * ── Why not just "random filenames" ───────────────────────────────────
 *
 * Renaming to a random name is necessary but not sufficient. The legacy system
 * returned the URL to the client, so the URL itself became the credential: it
 * leaked into browser history, Referer headers, and any screenshot. A signed
 * URL with a short TTL means the same link stops working.
 *
 * ── Storage root ──────────────────────────────────────────────────────
 *
 * Defaults outside `public/`. `UPLOAD_ROOT` can point at a mounted volume in
 * production, but resolve() plus the containment check below mean a bad value
 * cannot escape to somewhere web-served.
 */

const ROOT = resolve(process.env.UPLOAD_ROOT ?? join(process.cwd(), ".private-uploads"));

/** Hard cap per file. Aadhaar images are well under 2 MB. */
export const MAX_BYTES = 2 * 1024 * 1024;

const ALLOWED = new Map([
  ["image/jpeg", ".jpg"],
  ["image/png", ".png"],
  ["image/webp", ".webp"],
  ["application/pdf", ".pdf"],
]);

export type StoredFile = {
  key: OpaqueKey;
  bytes: number;
  contentType: string;
  storedAt: string;
};

function assertInsideRoot(key: string): string {
  const path = resolve(ROOT, normalize(key));
  // The key is generated by us, but it arrives from a URL, so verify it cannot
  // escape regardless of what it contains.
  if (path !== ROOT && !path.startsWith(ROOT + sep)) {
    throw new Error("Key escapes the upload root");
  }
  // Shape: <subject>.<base64url 20-32>.<ext>. The extension is required and
  // whitelisted rather than merely well-formed, so a stored .html or .svg can
  // never be written, and no key can be read back without proving its type is
  // one of the four we accept.
  if (!/^[A-Za-z0-9_-]{1,32}\.[A-Za-z0-9_-]{20,32}\.(jpg|png|webp|pdf)$/.test(key)) {
    throw new Error("Malformed key");
  }
  return path;
}

/** Write bytes to private storage. Rejects oversized and disallowed types. */
export async function put(
  subject: string,
  bytes: Buffer,
  contentType: string,
): Promise<StoredFile> {
  const ext = ALLOWED.get(contentType);
  if (!ext) {
    throw new Error(`Unsupported content type: ${contentType}`);
  }
  if (bytes.length === 0) throw new Error("Empty file");
  if (bytes.length > MAX_BYTES) {
    throw new Error(`File exceeds ${MAX_BYTES} bytes`);
  }

  const key = `${generateKey(subject)}${ext}`;
  const path = assertInsideRoot(key);
  await mkdir(dirname(path), { recursive: true });
  await rename(await writeTemp(bytes), path);

  return { key, bytes: bytes.length, contentType, storedAt: new Date().toISOString() };
}

/** Write to a temp name first, then rename, so a reader never sees a partial file. */
async function writeTemp(bytes: Buffer): Promise<string> {
  const tmp = join(ROOT, `.tmp-${randomUUID()}`);
  await mkdir(dirname(tmp), { recursive: true });
  // 0o600: owner-only. Even on a host with a permissive umask, nothing else
  // on the box can read an identity document.
  await writeFile(tmp, bytes, { mode: 0o600 });
  return tmp;
}

export async function read(key: string): Promise<Buffer> {
  return readFile(assertInsideRoot(key));
}

export function stream(key: string) {
  return createReadStream(assertInsideRoot(key));
}

export async function remove(key: string): Promise<void> {
  await unlink(assertInsideRoot(key));
}

export async function exists(key: string): Promise<boolean> {
  try {
    await stat(assertInsideRoot(key));
    return true;
  } catch {
    return false;
  }
}

export function contentTypeFor(key: string): string {
  if (key.endsWith(".jpg")) return "image/jpeg";
  if (key.endsWith(".png")) return "image/png";
  if (key.endsWith(".webp")) return "image/webp";
  if (key.endsWith(".pdf")) return "application/pdf";
  return "application/octet-stream";
}

export function uploadRoot(): string {
  return ROOT;
}
