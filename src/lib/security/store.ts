import { createReadStream } from "node:fs";
import { mkdir, readFile, rename, stat, unlink, writeFile } from "node:fs/promises";
import { dirname, join, normalize, resolve, sep } from "node:path";
import { randomUUID } from "node:crypto";
import { generateKey, type OpaqueKey } from "./sign.ts";

/**
 * Private file store for identity documents.
 *
 * ── The rule ──────────────────────────────────────────────────────────
 *
 * Nothing in here is ever served from a directory. There is no `public/`
 * mount and no static route. The only way to read a file is to redeem a valid
 * signed token whose subject matches the authenticated caller.
 *
 * ── Why not just "random filenames" ───────────────────────────────────
 *
 * Renaming to a random name is necessary but not sufficient. The legacy system
 * returned the URL to the client, so the URL itself became the credential: it
 * leaked into browser history, Referer headers, and any screenshot. A signed
 * URL with a short TTL means the same link stops working.
 *
 * ── Storage root ──────────────────────────────────────────────────────
 *
 * Defaults outside `public/`. `UPLOAD_ROOT` can point at a mounted volume in
 * production, but resolve() plus the containment check below mean a bad value
 * cannot escape to somewhere web-served.
 */

const ROOT = resolve(/*turbopackIgnore: true*/ process.env.UPLOAD_ROOT ?? join(process.cwd(), ".private-uploads"));

/* ── Object storage (optional) ─────────────────────────────────────────
 * Hosts without a writable disk (Vercel) set STORAGE_BUCKET plus the standard
 * AWS_* env vars; new files then live at `files/<key>` and legacy files at
 * `legacy/<path>` in that bucket. Unset, everything stays on disk. Key and
 * path validation runs first either way. */

const BUCKET = (process.env.STORAGE_BUCKET ?? "").trim();

let s3Client: import("@aws-sdk/client-s3").S3Client | null = null;
async function s3() {
  const sdk = await import("@aws-sdk/client-s3");
  s3Client ??= new sdk.S3Client({ forcePathStyle: true });
  return { sdk, client: s3Client };
}

async function s3Get(key: string): Promise<Buffer> {
  const { sdk, client } = await s3();
  const res = await client.send(new sdk.GetObjectCommand({ Bucket: BUCKET, Key: key }));
  return Buffer.from(await res.Body!.transformToByteArray());
}

/** Absolute cap per file; each upload kind has its own lower limit. */
export const MAX_BYTES = 50 * 1024 * 1024;

const ALLOWED = new Map([
  ["image/jpeg", ".jpg"],
  ["image/png", ".png"],
  ["image/webp", ".webp"],
  ["application/pdf", ".pdf"],
  ["video/mp4", ".mp4"],
  ["video/webm", ".webm"],
  ["video/quicktime", ".mov"],
]);

export type StoredFile = {
  key: OpaqueKey;
  bytes: number;
  contentType: string;
  storedAt: string;
};

function assertInsideRoot(key: string): string {
  assertKey(key);
  const path = resolve(ROOT, normalize(key));
  // The key is generated by us, but it arrives from a URL, so verify it cannot
  // escape regardless of what it contains.
  if (path !== ROOT && !path.startsWith(ROOT + sep)) {
    throw new Error("Key escapes the upload root");
  }
  return path;
}

function assertKey(key: string): void {
  // Shape: <subject>.<base64url 20-32>.<ext>. The extension is required and
  // whitelisted rather than merely well-formed, so a stored .html or .svg can
  // never be written, and no key can be read back without proving its type is
  // one of the four we accept.
  if (!/^[A-Za-z0-9_-]{1,40}\.[A-Za-z0-9_-]{20,32}\.(jpg|png|webp|pdf|mp4|webm|mov)$/.test(key)) {
    throw new Error("Malformed key");
  }
}

/** Write bytes to private storage. Rejects oversized and disallowed types. */
export async function put(
  subject: string,
  bytes: Buffer,
  contentType: string,
  maxBytes = MAX_BYTES,
): Promise<StoredFile> {
  const ext = ALLOWED.get(contentType);
  if (!ext) {
    throw new Error(`Unsupported content type: ${contentType}`);
  }
  if (bytes.length === 0) throw new Error("Empty file");
  if (bytes.length > Math.min(maxBytes, MAX_BYTES)) {
    throw new Error(`File exceeds ${maxBytes} bytes`);
  }

  const key = `${generateKey(subject)}${ext}`;
  if (BUCKET) {
    assertKey(key);
    const { sdk, client } = await s3();
    await client.send(new sdk.PutObjectCommand({ Bucket: BUCKET, Key: `files/${key}`, Body: bytes, ContentType: contentType }));
    return { key, bytes: bytes.length, contentType, storedAt: new Date().toISOString() };
  }
  const path = assertInsideRoot(key);
  await mkdir(dirname(path), { recursive: true });
  await rename(await writeTemp(bytes), path);

  return { key, bytes: bytes.length, contentType, storedAt: new Date().toISOString() };
}

/** Write to a temp name first, then rename, so a reader never sees a partial file. */
async function writeTemp(bytes: Buffer): Promise<string> {
  const tmp = join(ROOT, `.tmp-${randomUUID()}`);
  await mkdir(dirname(tmp), { recursive: true });
  // 0o600: owner-only. Even on a host with a permissive umask, nothing else
  // on the box can read an identity document.
  await writeFile(tmp, bytes, { mode: 0o600 });
  return tmp;
}

export async function read(key: string): Promise<Buffer> {
  if (BUCKET) {
    assertKey(key);
    return s3Get(`files/${key}`);
  }
  return readFile(/*turbopackIgnore: true*/ assertInsideRoot(key));
}

export function stream(key: string) {
  return createReadStream(/*turbopackIgnore: true*/ assertInsideRoot(key));
}

export async function remove(key: string): Promise<void> {
  if (BUCKET) {
    assertKey(key);
    const { sdk, client } = await s3();
    await client.send(new sdk.DeleteObjectCommand({ Bucket: BUCKET, Key: `files/${key}` }));
    return;
  }
  await unlink(assertInsideRoot(key));
}

export async function exists(key: string): Promise<boolean> {
  try {
    if (BUCKET) {
      assertKey(key);
      const { sdk, client } = await s3();
      await client.send(new sdk.HeadObjectCommand({ Bucket: BUCKET, Key: `files/${key}` }));
      return true;
    }
    await stat(/*turbopackIgnore: true*/ assertInsideRoot(key));
    return true;
  } catch {
    return false;
  }
}

export function contentTypeFor(key: string): string {
  if (key.endsWith(".jpg")) return "image/jpeg";
  if (key.endsWith(".png")) return "image/png";
  if (key.endsWith(".webp")) return "image/webp";
  if (key.endsWith(".pdf")) return "application/pdf";
  if (key.endsWith(".mp4")) return "video/mp4";
  if (key.endsWith(".webm")) return "video/webm";
  if (key.endsWith(".mov")) return "video/quicktime";
  return "application/octet-stream";
}

export function uploadRoot(): string {
  return ROOT;
}

/* ── Legacy uploads (read-only) ────────────────────────────────────────
 * The legacy app wrote `<ms>-<uuid>.<ext>` (or `<uuid>.<ext>`) into
 * uploads/ and three subfolders, and stored `/uploads/...` paths in the DB.
 * Those files are served only through /api/files/legacy, which checks who
 * may see each one; nothing here is a static mount. */

const LEGACY_ROOT = resolve(/*turbopackIgnore: true*/ process.env.LEGACY_UPLOAD_ROOT ?? join(process.cwd(), ".legacy-uploads"));
const LEGACY_NAME = /^(?:(academics|company-logos|support)\/)?(?:\d{10,16}-)?[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpe?g|png|webp|pdf|docx|mp4|webm|mov)$/i;

/** Normalised legacy path ("academics/x.jpg") or null if it isn't one. */
export function legacyPath(raw: string): { path: string; folder: string | null } | null {
  const path = raw.replace(/^\/?uploads\//, "").replace(/^\/+/, "");
  const m = LEGACY_NAME.exec(path);
  if (!m) return null;
  const abs = resolve(LEGACY_ROOT, path);
  if (!abs.startsWith(LEGACY_ROOT + sep)) return null;
  return { path, folder: m[1] ?? null };
}

export async function readLegacy(path: string): Promise<Buffer> {
  const ok = legacyPath(path);
  if (!ok) throw new Error("Malformed legacy path");
  if (BUCKET) return s3Get(`legacy/${ok.path}`);
  return readFile(/*turbopackIgnore: true*/ resolve(LEGACY_ROOT, ok.path));
}

const LEGACY_TYPES: Record<string, string> = {
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  png: "image/png",
  webp: "image/webp",
  pdf: "application/pdf",
  docx: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  mp4: "video/mp4",
  webm: "video/webm",
  mov: "video/quicktime",
};

export function legacyContentType(path: string): string {
  return LEGACY_TYPES[path.split(".").pop()?.toLowerCase() ?? ""] ?? "application/octet-stream";
}

/** Read a stored file by whatever name the DB holds: a new key or a legacy name. */
export async function readAny(name: string): Promise<{ bytes: Buffer; contentType: string }> {
  if (legacyPath(name)) return { bytes: await readLegacy(name), contentType: legacyContentType(name) };
  return { bytes: await read(name), contentType: contentTypeFor(name) };
}
